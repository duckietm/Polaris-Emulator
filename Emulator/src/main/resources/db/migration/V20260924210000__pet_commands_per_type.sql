-- Every pet type gets its own trainable commands.
--
-- `pet_commands` maps a pet type to the commands its training panel offers and
-- its owner can give in chat. The base schema seeded it for the dragon (12)
-- only, so every other type opened an empty training panel and ignored every
-- command. The lists below give each of the 36 types in `pet_actions` its set:
-- the shared basics (free, sit, down, here, stay, follow, drink, eat...) plus
-- the tricks of its kind, such as the chick's chicken dance, the frog's croak
-- and mambo, the spider's bounce and flatten, and the dragon's fire.
--
-- The table had no key, so the same pair could be stored many times and the
-- panel then showed the same command once per copy. The primary key on
-- (pet_id, command_id) is added with ALTER IGNORE, which keeps one row per
-- pair and drops only the exact copies; no pair a hotel configured is lost.
--
-- Idempotent and additive: an existing primary key is left as it is, rows are
-- inserted with INSERT IGNORE so a hotel's own additions stay, and only
-- command ids that exist in `pet_commands_data` are inserted, because the
-- loader would otherwise put a missing command into the pet's list.

SET @polaris_pet_commands_pk = (
    SELECT COUNT(*)
    FROM information_schema.TABLE_CONSTRAINTS
    WHERE TABLE_SCHEMA = DATABASE()
      AND TABLE_NAME = 'pet_commands'
      AND CONSTRAINT_TYPE = 'PRIMARY KEY'
);
SET @polaris_pet_commands_pk_sql = IF(
    @polaris_pet_commands_pk > 0,
    'DO 0',
    'ALTER IGNORE TABLE `pet_commands` ADD PRIMARY KEY (`pet_id`, `command_id`)'
);
PREPARE polaris_pet_commands_pk_statement FROM @polaris_pet_commands_pk_sql;
EXECUTE polaris_pet_commands_pk_statement;
DEALLOCATE PREPARE polaris_pet_commands_pk_statement;

